// scripts/fetchAreas.mjs
// Regenerates the generated area files in src/configs/ from FWC's public map services.
// Run with: node scripts/fetchAreas.mjs
import { writeFileSync } from 'node:fs';

const FWC = 'https://gis.myfwc.com/hosting/rest/services/Open_Data';

// simplifyDeg keeps vertex counts low enough for pathfinding and file size (0.001 is ~100 m)
const DATASETS = [
    {
        file: 'reefsConfig.js',
        exportName: 'FLORIDA_REEFS',
        idPrefix: 'reef-fwc',
        title: 'Unified Florida Reef Tract Map: aggregate reefs and ridges of at least 1 km²',
        source: `${FWC}/Unified_Florida_Reef_Tract_Benthic_Habitat/MapServer/16`,
        where: "ClassLv1 IN ('Aggregate Reef','Ridge') AND Shape_Area >= 1000000",
        outFields: 'OBJECTID,ClassLv2,Source',
        simplifyDeg: 0.001,
        name: (properties) => `${properties.ClassLv2} (${properties.Source})`,
    },
    {
        file: 'landConfig.js',
        exportName: 'FLORIDA_LAND',
        idPrefix: 'land-fwc',
        title: 'Florida Shoreline (1:40,000): mainland, keys and islands of at least 0.25 km²',
        source: `${FWC}/Florida_Shoreline_1to40000_Scale_Polygon/MapServer/3`,
        where: "ATTRIBUTE = 'Land' AND SHAPE_Area >= 250000",
        outFields: 'OBJECTID',
        simplifyDeg: 0.003,
        name: () => 'Land',
    },
];

for (const dataset of DATASETS) {
    const params = new URLSearchParams({
        where: dataset.where,
        outFields: dataset.outFields,
        outSR: '4326',
        maxAllowableOffset: String(dataset.simplifyDeg),
        geometryPrecision: '4',
        f: 'geojson',
    });
    const response = await fetch(`${dataset.source}/query?${params}`);
    const geojson = await response.json();
    if (!response.ok || geojson.error || !geojson.features) {
        throw new Error(`${dataset.file}: query failed: ${JSON.stringify(geojson.error ?? response.status)}`);
    }
    // shortcut: single request, no paging. Upgrade if a query grows past the server's 2000 row limit.
    if (geojson.exceededTransferLimit || geojson.properties?.exceededTransferLimit) {
        throw new Error(`${dataset.file}: more rows than one request returns, add paging or narrow the query`);
    }

    const areas = [];
    for (const { properties, geometry } of geojson.features) {
        // Our areas are single rings: split multipolygons and keep only each part's outer ring (holes dropped)
        const polygons = geometry.type === 'MultiPolygon' ? geometry.coordinates : [geometry.coordinates];
        polygons.forEach(([outerRing], part) => {
            // GeoJSON is [lon, lat] with a repeated closing vertex; our format is [lat, lon], unclosed
            const coordinates = outerRing.slice(0, -1).map(([lon, lat]) => [lat, lon]);
            if (coordinates.length < 3) return;
            // Simplification leaves some multipolygon parts as slivers smaller than its own tolerance, skip them
            const lats = coordinates.map(([lat]) => lat), lons = coordinates.map(([, lon]) => lon);
            if (Math.max(...lats) - Math.min(...lats) < dataset.simplifyDeg && Math.max(...lons) - Math.min(...lons) < dataset.simplifyDeg) return;
            areas.push({
                id: `${dataset.idPrefix}-${properties.OBJECTID}${polygons.length > 1 ? `-${part + 1}` : ''}`,
                name: dataset.name(properties),
                coordinates,
            });
        });
    }

    const entries = areas.map(area =>
        `\t{ id: ${JSON.stringify(area.id)}, name: ${JSON.stringify(area.name)}, coordinates: ${JSON.stringify(area.coordinates)} },`
    );
    writeFileSync(new URL(`../src/configs/${dataset.file}`, import.meta.url), `// src/configs/${dataset.file}
// GENERATED by scripts/fetchAreas.mjs, do not edit by hand.
// Source: Florida Fish and Wildlife Conservation Commission (FWC-FWRI)
// ${dataset.title}, simplified to ~${dataset.simplifyDeg * 100000} m.
// ${dataset.source}

export const ${dataset.exportName} = [
${entries.join('\n')}
];
`);

    const vertices = areas.reduce((sum, area) => sum + area.coordinates.length, 0);
    console.log(`${dataset.file}: ${geojson.features.length} features -> ${areas.length} areas, ${vertices} vertices`);
}
