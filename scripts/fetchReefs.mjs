// scripts/fetchReefs.mjs
// Regenerates src/configs/reefsConfig.js from FWC's Unified Florida Reef Tract map.
// Run with: node scripts/fetchReefs.mjs
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://gis.myfwc.com/hosting/rest/services/Open_Data/Unified_Florida_Reef_Tract_Benthic_Habitat/MapServer/16';
const MIN_AREA_M2 = 1_000_000;  // "major" reefs only: at least 1 km²
const SIMPLIFY_DEG = 0.001;     // ~100 m, keeps vertex counts low enough for pathfinding

const params = new URLSearchParams({
    where: `ClassLv1 IN ('Aggregate Reef','Ridge') AND Shape_Area >= ${MIN_AREA_M2}`,
    outFields: 'OBJECTID,ClassLv2,Source,Shape_Area',
    orderByFields: 'Shape_Area DESC',
    outSR: '4326',
    maxAllowableOffset: String(SIMPLIFY_DEG),
    geometryPrecision: '4',
    f: 'geojson',
});
const response = await fetch(`${SOURCE}/query?${params}`);
const geojson = await response.json();
if (!response.ok || geojson.error || !geojson.features) {
    throw new Error(`Reef query failed: ${JSON.stringify(geojson.error ?? response.status)}`);
}
// shortcut: single request, no paging. Upgrade if MIN_AREA_M2 is lowered past the server's 2000 row limit.
if (geojson.exceededTransferLimit || geojson.properties?.exceededTransferLimit) {
    throw new Error('More reefs than one request returns: add paging or raise MIN_AREA_M2');
}

const reefs = [];
for (const { properties, geometry } of geojson.features) {
    // Our areas are single rings: split multipolygons and keep only each part's outer ring (holes dropped)
    const polygons = geometry.type === 'MultiPolygon' ? geometry.coordinates : [geometry.coordinates];
    polygons.forEach(([outerRing], part) => {
        // GeoJSON is [lon, lat] with a repeated closing vertex; our format is [lat, lon], unclosed
        const coordinates = outerRing.slice(0, -1).map(([lon, lat]) => [lat, lon]);
        if (coordinates.length < 3) return;
        // Simplification leaves some multipolygon parts as slivers smaller than its own tolerance, skip them
        const lats = coordinates.map(([lat]) => lat), lons = coordinates.map(([, lon]) => lon);
        if (Math.max(...lats) - Math.min(...lats) < SIMPLIFY_DEG && Math.max(...lons) - Math.min(...lons) < SIMPLIFY_DEG) return;
        reefs.push({
            id: `reef-fwc-${properties.OBJECTID}${polygons.length > 1 ? `-${part + 1}` : ''}`,
            name: `${properties.ClassLv2} (${properties.Source})`,
            coordinates,
        });
    });
}

const entries = reefs.map(reef =>
    `\t{ id: ${JSON.stringify(reef.id)}, name: ${JSON.stringify(reef.name)}, coordinates: ${JSON.stringify(reef.coordinates)} },`
);
writeFileSync(new URL('../src/configs/reefsConfig.js', import.meta.url), `// src/configs/reefsConfig.js
// GENERATED by scripts/fetchReefs.mjs, do not edit by hand.
// Source: Unified Florida Reef Tract Map, Florida Fish and Wildlife Conservation Commission (FWC-FWRI)
// ${SOURCE}
// Aggregate reefs and ridges of at least ${MIN_AREA_M2 / 1e6} km², simplified to ~${SIMPLIFY_DEG * 100000} m.

export const FLORIDA_REEFS = [
${entries.join('\n')}
];
`);

const vertices = reefs.reduce((sum, reef) => sum + reef.coordinates.length, 0);
console.log(`${geojson.features.length} features -> ${reefs.length} areas, ${vertices} vertices`);
